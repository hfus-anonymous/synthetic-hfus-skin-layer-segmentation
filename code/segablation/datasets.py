from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import cv2
import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset

from .common import read_json, read_rgb, read_gray, resize_image_and_mask, v66_to_epi_sleb


def _as_samples(meta: Any) -> List[Dict[str, Any]]:
    """Return a list of sample dictionaries from supported metadata formats."""
    if isinstance(meta, dict) and isinstance(meta.get("samples"), list):
        return list(meta["samples"])
    if isinstance(meta, list):
        return list(meta)
    if isinstance(meta, dict):
        # Fallback for metadata stored as {sample_id: sample_record}.
        out: List[Dict[str, Any]] = []
        for k, v in meta.items():
            if isinstance(v, dict) and ("image" in v or "image_path" in v or "mask" in v or "mask_path" in v):
                vv = dict(v)
                vv.setdefault("id", k)
                out.append(vv)
        if out:
            return out
    raise ValueError("Unsupported metadata.json format. Expected {'samples': [...]} or list/dict of sample records.")


def _get_sample_id(s: Dict[str, Any]) -> str:
    for key in ("id", "sample_id", "name"):
        val = s.get(key)
        if val is not None and str(val) != "":
            return str(val)
    img = str(s.get("image") or s.get("image_path") or "sample")
    return Path(img).stem.replace("_mask", "")


def _path_value(s: Dict[str, Any], kind: str) -> str:
    if kind == "image":
        keys = ("image", "image_path", "img", "img_path", "file", "filename")
    elif kind == "mask":
        keys = ("mask", "mask_path", "label", "label_path", "target", "target_path")
    else:
        raise ValueError(kind)
    for key in keys:
        val = s.get(key)
        if val is not None and str(val) != "":
            return str(val)
    sid = _get_sample_id(s)
    if kind == "image":
        return f"images/{sid}.png"
    return f"masks/{sid}_mask.png"


def _resolve(root: Path, p: str) -> Path:
    pp = Path(p)
    if pp.is_absolute():
        return pp
    return root / pp


def infer_source(s: Dict[str, Any]) -> str:
    """Infer original/augmented robustly.

    Supports both the full dataset naming scheme such as ``1_00_original`` and
    the re-numbered public sample metadata generated by ``code/make_sample.py``.
    """
    for key in ("source", "sample_source", "source_type"):
        val = s.get(key)
        if val is not None and str(val).strip() != "":
            v = str(val).strip().lower()
            if v in {"original", "orig", "00_original", "none"}:
                return "original"
            if v in {"augmented", "augmentation", "aug"}:
                return "augmented"

    for key in ("augmentation_type", "augmentation_anchor", "augmentation_name", "aug_type", "transform"):
        val = s.get(key)
        if val is not None and str(val).strip() != "":
            v = str(val).strip().lower()
            if v in {"original", "orig", "none", "00_original"} or "00_original" in v:
                return "original"
            return "augmented"

    text = " ".join([
        _get_sample_id(s),
        _path_value(s, "image"),
        _path_value(s, "mask"),
        str(s.get("source_sample_id", "")),
        str(s.get("renumbered_from_id", "")),
    ]).lower()
    if "_00_original" in text or text.endswith("original") or "00-original" in text:
        return "original"
    return "augmented"


class V66MetadataDataset(Dataset):
    """Dataset for augmented V66 metadata.json.

    Supports 8-class masks for Experiment A or epi/SLEB/other mapped masks for B.
    Train should generally use sources=["original", "augmented"] from data/augmented.
    Main val/test should use sources=["original"] from data/augmented to avoid
    evaluating on augmented derivatives.
    """

    def __init__(
        self,
        root: str | Path,
        split: Optional[str],
        sources: Optional[Sequence[str]],
        size_hw: Tuple[int, int],
        mode: str = "8class",
        metadata_name: str = "metadata.json",
        rgb: bool = True,
    ) -> None:
        self.root = Path(root)
        self.meta = read_json(self.root / metadata_name)
        samples = _as_samples(self.meta)
        # Normalize path, id, and source so later code is independent of metadata dialect.
        norm_samples: List[Dict[str, Any]] = []
        for s0 in samples:
            if not isinstance(s0, dict):
                continue
            s = dict(s0)
            s.setdefault("id", _get_sample_id(s))
            s["image"] = _path_value(s, "image")
            s["mask"] = _path_value(s, "mask")
            s["source"] = infer_source(s)
            norm_samples.append(s)
        samples = norm_samples
        if split is not None:
            samples = [s for s in samples if str(s.get("split", "")).lower() == str(split).lower()]
        if sources is not None:
            src_set = {str(x).lower() for x in sources}
            samples = [s for s in samples if str(s.get("source", "")).lower() in src_set]
        if not samples:
            raise ValueError(f"No samples found: root={root}, split={split}, sources={sources}. Check split/source fields and that data/augmented contains *_00_original samples.")
        if mode not in {"8class", "epi_sleb"}:
            raise ValueError("mode must be 8class or epi_sleb")
        self.samples = samples
        self.size_hw = tuple(size_hw)
        self.mode = mode
        self.rgb = rgb

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int):
        s = self.samples[idx]
        img = read_rgb(_resolve(self.root, s["image"]))
        mask = read_gray(_resolve(self.root, s["mask"]))
        if self.mode == "epi_sleb":
            mask = v66_to_epi_sleb(mask)
        img, mask = resize_image_and_mask(img, mask, self.size_hw)
        img = img.astype(np.float32) / 255.0
        if self.rgb:
            img_t = torch.from_numpy(img).permute(2, 0, 1).float()
        else:
            gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
            img_t = torch.from_numpy(gray[None, ...]).float()
        mask_t = torch.from_numpy(mask.astype(np.int64)).long()
        return img_t, mask_t, s


class ImageMaskFolderDataset(Dataset):
    """Dataset from a CSV manifest with image, mask, split fields."""

    def __init__(
        self,
        manifest_csv: str | Path,
        split: Optional[str] = None,
        size_hw: Optional[Tuple[int, int]] = None,
        rgb: bool = True,
    ) -> None:
        self.manifest_csv = Path(manifest_csv)
        df = pd.read_csv(self.manifest_csv)
        if split is not None and "split" in df.columns:
            df = df[df["split"].astype(str).str.lower() == str(split).lower()].copy()
        if df.empty:
            raise ValueError(f"No rows in manifest={manifest_csv} for split={split}")
        self.rows = df.to_dict("records")
        self.size_hw = size_hw
        self.rgb = rgb

    def __len__(self) -> int:
        return len(self.rows)

    def __getitem__(self, idx: int):
        r = self.rows[idx]
        img = read_rgb(r["image"])
        mask = read_gray(r["mask"])
        if self.size_hw is not None:
            img, mask = resize_image_and_mask(img, mask, self.size_hw)
        img = img.astype(np.float32) / 255.0
        if self.rgb:
            img_t = torch.from_numpy(img).permute(2, 0, 1).float()
        else:
            gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
            img_t = torch.from_numpy(gray[None, ...]).float()
        return img_t, torch.from_numpy(mask.astype(np.int64)).long(), r


def collate_with_meta(batch):
    images = torch.stack([x[0] for x in batch], dim=0)
    masks = torch.stack([x[1] for x in batch], dim=0)
    meta = [x[2] for x in batch]
    return images, masks, meta
